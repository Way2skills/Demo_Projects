function createDemoWarranty(product) {
  const duration =
    product.slug
      .split("")
      .reduce((total, character) => total + character.charCodeAt(0), 0) %
      2 +
    1;

  return {
    duration: { value: duration, unit: duration === 1 ? "year" : "years" },
    type: "Demo-only duration; not manufacturer or retailer verified",
    demoOnly: true,
    verified: false,
  };
}

function createWatch(product) {
  const categories = product.categorySlugs.map((slug) => {
    const name = categoryNames.get(slug);
    if (!name) {
      throw new Error(`Unknown watch category slug: ${slug}`);
    }
    return name;
  });

  return {
    gender: null,
    watchType: null,
    strapMaterial: null,
    dialColour: null,
    dialSize: null,
    dialShape: null,
    screenSize: null,
    caseShape: null,
    displayType: null,
    batteryLife: null,
    connectivity: null,
    compatibleDevices: null,
    sensors: null,
    chargingType: null,
    price: null,
    availability: null,
    movement: null,
    caseMaterial: null,
    caseDiameter: null,
    waterResistance: null,
    imagePath: null,
    warranty: null,
    badge: null,
    shortDescription: null,
    isFeatured: false,
    ...product,
    categories,
    warranty:
      product.warranty ??
      (product.brand === "Rolex"
        ? rolexWarranty
        : product.brand === "Omega"
          ? omegaWarranty
          : createDemoWarranty(product)),
  };
}

