/**
 * Helper: Find watch by its slug
 */
export function getWatchBySlug(slug) {
  return watches.find((watch) => watch.slug === slug);
}

/**
 * Helper: Get featured watches for homepage
 */
export function getFeaturedWatches() {
  return watches.filter((watch) => watch.isFeatured);
}

/**
 * Helper: Get watches by brand slug
 */
export function getWatchesByBrand(brandSlug) {
  return watches.filter((watch) => watch.brandSlug === brandSlug);
}

/**
 * Helper: Get watches by category slug
 */
export function getWatchesByCategory(categorySlug) {
  return watches.filter((watch) => watch.categorySlugs.includes(categorySlug));
}